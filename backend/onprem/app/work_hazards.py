"""工項名稱 → 應注意的危害類別。

為什麼需要這個
--------------
牆上只顯示「C區第一二節鋼構輪吊」對值班人員不夠——長官要的是
「現在在做什麼、**要注意什麼**」。工項名稱本身就帶著危害資訊
（吊裝→墜落與物體飛落、開挖→倒塌），用關鍵字對應把它翻出來。

只做提示、不做判定
------------------
這裡的輸出是「這類作業常見的危害」，不是風險評估。真正的管制依據是
各工項的自主檢查表與作業許可，牆上的標籤只負責讓人抬頭。
因此對不到關鍵字就回空清單，不硬湊——錯的提醒比沒有提醒更糟，
現場會學會忽略它。

詞彙沿用缺失統計的災害類別（墜落、物體飛落…），讓牆上前後兩區
講同一種語言。
"""

from __future__ import annotations

from typing import List

# (關鍵字們, 對應的危害標籤們)。由上而下比對，全部命中的聯集取前三個。
# 關鍵字取「工程用語的字根」：塔吊/輪吊/吊裝都含「吊」，一條規則涵蓋。
_RULES = [
    (("吊",),                    ["起重吊掛", "物體飛落"]),
    (("爬升",),                  ["高處墜落"]),
    (("鋼構", "鐵件"),           ["高處墜落", "物體飛落"]),
    (("施工架", "鷹架", "三腳架"), ["高處墜落"]),
    (("帷幕", "外牆"),           ["高處墜落", "物體飛落"]),
    (("模板",),                  ["倒塌崩塌", "高處墜落"]),
    (("鋼筋",),                  ["穿刺", "物體飛落"]),
    (("RC", "灌漿", "混凝土", "澆置"), ["倒塌崩塌", "感電"]),
    (("開挖", "土方", "擋土", "支撐"), ["倒塌崩塌"]),
    (("拆除", "打除",),          ["倒塌崩塌", "物體飛落"]),
    (("電銲", "焊",),            ["火災爆炸", "感電"]),
    (("防水", "油漆", "塗裝"),   ["火災爆炸"]),
    (("機電", "配線", "配管", "水電"), ["感電"]),
]


def hazards_of(task_name: str) -> List[str]:
    """依工項名稱列出應注意的危害，最多三項。對不到就回空清單。"""
    name = (task_name or "").upper()      # RC 這類英文字根不分大小寫
    out: List[str] = []
    for keys, labels in _RULES:
        if any(k.upper() in name for k in keys):
            for lb in labels:
                if lb not in out:
                    out.append(lb)
    return out[:3]


