"""熱危害風險等級對應的應辦措施（地端版）。

依據勞動部職業安全衛生署《高氣溫作業熱危害預防指引》
（108.1.28 訂定，114.6.20 勞職授字第 1140252820 號第 2 次修正）
附表二「熱危害風險等級對應之熱指數及風險管理原則」與
附表三「不同熱危害風險等級對應之危害預防及管理措施表」。

為什麼要把措施寫進系統
----------------------
只顯示「第三級」對現場沒有用——值班人員未必記得第三級要做什麼。
牆上要直接講出「現在該做哪幾件事」，指引才會變成行動。

等級判定本身在 hazard.py（門檻取自附表二，不可自行四捨五入）。
本檔只負責「這一級要做什麼」。
"""

from __future__ import annotations

from typing import Dict, List, Optional

from .hazard import level_of

# 附表三中各級都要做的基礎措施
BASE_MEASURES: List[str] = [
    "降低勞工暴露溫度：遮陽、風扇、水霧等降溫設施",
    "指派專人定期巡視作業情形，隨時掌握勞工健康狀況",
    "提供鄰近、遮陽且能降溫的休息場所",
    "提供淺色、寬鬆、透氣排汗之工作服與通風帽盔",
    "於作業場所提供充足飲用水及電解質",
    "適當選配作業勞工，確認其身體健康狀況",
    "實施熱危害預防教育訓練",
    "建立緊急應變處理機制與急救措施",
]

LEVEL2_ADD = [
    "調整勞工熱適應能力（新進人員應逐日增加熱暴露時間）",
    "調整勞工作業時間，減少連續作業，避開高氣溫時段",
]
LEVEL3_ADD = [
    "避免使勞工於高氣溫時段從事戶外作業",
    "必要時選用個人防護器具（冰背心、風扇背心等），但這是最後一道防線",
]
LEVEL4_ADD = [
    "避免使勞工從事戶外作業",
    "確有必要時應加強緊急應變機制",
    "依設施規則第 303 條之 1 設置遮陽、降溫設備及適當休息場所",
    "避免穿著不透氣厚重防護衣作業，避免重體力作業",
]

# 指引裡有明確數字、現場最需要被提醒的幾件事。
# 陽光直照要提升一級的規定不放這裡——它由 escalated() 另外算出實際會提升到
# 第幾級並單獨顯示，講得比一句原則更有用，兩邊都寫只是佔掉牆面。
COMMON_REMINDERS = [
    "補充水分：每 15～20 分鐘 1 次、每次 150～200 毫升，規律執行而非口渴才喝",
    "重體力作業：每小時至少給予 20 分鐘充足休息",
]

# 各級相較前一級「多」要求的事。牆上空間有限，把八項每級都要做的基本措施
# 全列出來，反而看不出這一級的重點在哪；完整清單留給彈出提醒。
_FOCUS: Dict[int, List[str]] = {
    0: [],
    1: ["遮陽降溫、定期巡視、充足飲水與電解質等基本防護",
        "從事重體力作業時應特別提高警覺"],
    2: LEVEL2_ADD,
    3: LEVEL3_ADD,
    4: LEVEL4_ADD,
}

_NAME = {0: "未達第一級", 1: "第一級", 2: "第二級", 3: "第三級", 4: "第四級"}

_PRINCIPLE = {
    0: "尚未達指引所定風險等級，維持一般作業管理即可。",
    1: "熱暴露之基本防護與原則；從事重體力作業時應提高警覺。",
    2: "實施危害預防措施及提升危害認知。",
    3: "強化採取之危害預防及管理措施，並注意勞工身體狀況。",
    4: "更積極執行相關防護措施，原則上避免使勞工從事戶外作業。",
}

# 累積措施由各級的增量推導，不逐級手抄。手抄的話，之後在第二級插入一項
# 措施要同時改三行，漏掉任何一行都會讓某一級少列一項法定措施——而牆上
# 一次只顯示一級，看不出來。
_ADDED: Dict[int, List[str]] = {
    0: [], 1: BASE_MEASURES, 2: LEVEL2_ADD, 3: LEVEL3_ADD, 4: LEVEL4_ADD,
}


def _measures(level: int) -> List[str]:
    out: List[str] = []
    for i in range(1, level + 1):
        out.extend(_ADDED[i])
    return out


def _pack(level: int) -> dict:
    return {
        "level": level,
        "name": _NAME[level],
        "principle": _PRINCIPLE[level],
        "measures": _measures(level),
        "focus": _FOCUS[level],
        "reminders": [] if level == 0 else COMMON_REMINDERS,
    }


def heat_guidance(heat_index) -> Optional[dict]:
    """依熱指數值取得該級的應辦措施。無有效值時回 None。"""
    if heat_index is None:
        return None
    level = level_of("heat_index", heat_index)
    g = _pack(level)
    g["value"] = heat_index

    # 附表二備註三：陽光直照或穿不透氣防護衣應提升一級。工地戶外作業多屬
    # 前者，只顯示現值會讓現場低估；但是否成立要由現場認定，因此並列顯示
    # 而不直接取代判定結果。第六點把適用範圍定在第一級至第三級。
    g["if_direct_sun"] = _pack(level + 1) if 1 <= level <= 3 else None
    return g
